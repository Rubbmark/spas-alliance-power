CREATE TABLE IF NOT EXISTS members (
 id TEXT PRIMARY KEY, key_hash TEXT UNIQUE NOT NULL,
 name TEXT NOT NULL COLLATE NOCASE UNIQUE, profession TEXT NOT NULL, rank TEXT NOT NULL, role TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS entries (
 member TEXT NOT NULL REFERENCES members(id), week TEXT NOT NULL, power INTEGER NOT NULL CHECK(power>0),
 PRIMARY KEY(member,week)
);
